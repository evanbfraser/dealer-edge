const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CSS_DIR = path.join(ROOT, 'css');
const SOURCE_PATH = path.join(CSS_DIR, 'sales.css');
const css = fs.readFileSync(SOURCE_PATH, 'utf8');

function readSlice(startMarker, endMarker) {
  const start = css.indexOf(startMarker);
  if (start === -1) throw new Error(`Missing start marker: ${startMarker}`);
  const end = endMarker ? css.indexOf(endMarker, start + startMarker.length) : css.length;
  if (endMarker && end === -1) throw new Error(`Missing end marker: ${endMarker}`);
  return css.slice(start, end).trim();
}

function readSliceAfter(afterMarker, startMarker, endMarker) {
  const after = css.indexOf(afterMarker);
  if (after === -1) throw new Error(`Missing after marker: ${afterMarker}`);
  const start = css.indexOf(startMarker, after + afterMarker.length);
  if (start === -1) throw new Error(`Missing start marker after ${afterMarker}: ${startMarker}`);
  const end = endMarker ? css.indexOf(endMarker, start + startMarker.length) : css.length;
  if (endMarker && end === -1) throw new Error(`Missing end marker: ${endMarker}`);
  return css.slice(start, end).trim();
}

function stripBetween(input, startMarker, endMarker) {
  const start = input.indexOf(startMarker);
  if (start === -1) return input;
  const end = input.indexOf(endMarker, start + startMarker.length);
  if (end === -1) return input.slice(0, start);
  return input.slice(0, start) + input.slice(end);
}

function write(file, body, purpose) {
  const header = `/* Generated by scripts/build-sales-css.js.
   Source: css/sales.css
   Purpose: ${purpose}. */
`;
  const output = `${header}\n${body.trim()}\n`;
  fs.writeFileSync(path.join(CSS_DIR, file), output, 'utf8');
  console.log(`${file}: ${Buffer.byteLength(output)} bytes`);
}

let heroBase = readSlice(
  '/* ═══════════════════════════════════════════════════════════════',
  '/* ═══════════════════════════════════════════════════════════════\r\n   MARINE REALITY'
);

// Keep the current prehero + pinned cohort styles critical. Exclude legacy
// standalone hero/proof/chapter blocks that are not present in sales.html.
heroBase = stripBetween(
  heroBase,
  '/* Legacy standalone hero (unused',
  '.s-hero-grid {'
);
heroBase = heroBase
  .replace(/\/\* ─── PROOF CHAIN BAND[\s\S]*?(?=\/\* ═{10,}[\s\S]*?STATS SECTION)/, '')
  .replace(/\/\* ─── Chapter divider[\s\S]*?(?=@media \(prefers-reduced-motion: reduce\))/, '');

const statsResponsive = readSlice(
  '/* ─── responsive overrides for stats section + marine',
  '/* ─── ACT SECTIONS'
);

// The mobile cohort CARD/GRID layout (grid-template-areas, .s-cohort-row
// display:contents, the aspect-ratio grid, and the 600vh mobile pin height)
// lives inside a below-fold @media block, so it was landing in sales-late —
// but the cohort IS the above-the-fold hero. Without it, the grid collapses to
// width:0 on mobile first paint (blank card) until the late CSS loads. Pull the
// marked block into critical, re-wrapped in its media query. It stays in the
// late bundle too (identical rules, harmless duplicate).
const mobileCohortHero = readSlice(
  '/* ─── MOBILE COHORT HERO START (pulled into sales-critical) ─── */',
  '/* ─── MOBILE COHORT HERO END ─── */'
)
  .replace('/* ─── MOBILE COHORT HERO START (pulled into sales-critical) ─── */', '')
  .trim();
const mobileCohortHeroCritical = `@media (max-width: 1100px) {\n${mobileCohortHero}\n}`;

const monoFontFace = `@font-face {
  font-family: 'JetBrains Mono';
  src: url('../assets/fonts/jetbrains-mono-var-latin.woff2') format('woff2');
  font-weight: 400 600;
  font-style: normal;
  font-display: swap;
}`;

write(
  'sales-critical.css',
  [monoFontFace, heroBase, statsResponsive, mobileCohortHeroCritical].join('\n\n'),
  'critical hook and pinned cohort hero CSS'
);

write(
  'sales-late.css',
  readSlice('/* ═══════════════════════════════════════════════════════════════\r\n   MARINE REALITY', null),
  'below-fold sales proof, act visuals, SMS demo, pivots, and lower sections'
);
