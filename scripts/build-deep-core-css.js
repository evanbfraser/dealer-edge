const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const STYLE_PATH = path.join(ROOT, 'css', 'style.css');
const OUT_PATH = path.join(ROOT, 'css', 'deep-core.css');
const VIDEO_BOAT_OUT_PATH = path.join(ROOT, 'css', 'video-boat.css');
const FEATURES_DEPT_OUT_PATH = path.join(ROOT, 'css', 'features-dept.css');

const css = fs.readFileSync(STYLE_PATH, 'utf8');

const slices = [
  ['/* ─── VARIABLES ─── */', '/* ─── VIDEO SECTION ─── */'],
  ['/* ─── RESET ─── */', '/* ─── HERO ─── */'],
  ['/* ─── BUTTONS ─── */', '/* ─── FEATURES ─── */'],
  ['.features-cta-actions {', '/* ─── JOURNEY / TOUCHPOINTS ─── */'],
  ['/* ─── CTA ─── */', '/* ─── CHATBOT ─── */'],
  ['/* ─── MODAL ─── */', '/* ─── PRICING PAGE ─── */'],
  ['/* ─── MOBILE NAV ─── */', '/* ─── VIDEO + BOAT RESPONSIVE ─── */'],
  ['/* ─── MODAL MOBILE ─── */', null],
];

const videoBoatSlices = [
  ['/* ─── VIDEO SECTION ─── */', '/* ─── HERO ─── */'],
  ['/* ─── BOAT SECTION ─── */', '/* ─── STATS ─── */'],
  ['/* ─── VIDEO + BOAT RESPONSIVE ─── */', '/* ─── MODAL MOBILE ─── */'],
];

function readSlice(startMarker, endMarker) {
  const start = css.indexOf(startMarker);
  if (start === -1) {
    throw new Error(`Missing start marker: ${startMarker}`);
  }
  const end = endMarker ? css.indexOf(endMarker, start + startMarker.length) : css.length;
  if (endMarker && end === -1) {
    throw new Error(`Missing end marker: ${endMarker}`);
  }
  return css.slice(start, end).trim();
}

const header = `/* Generated by scripts/build-deep-core-css.js.
   Source: css/style.css
   Purpose: lean shared CSS for immersive deep-dive pages. */
`;

const placeholders = `/* Initial geometry placeholders for the lazy video/boat section CSS. */
.boat-section { height: 300vh; background: #000; }
@media (max-width: 960px) { .boat-section { height: 200vh; } }
@media (max-width: 640px) { .boat-section { height: 200vh; } }
`;
const deepBody = slices.map(([start, end]) => readSlice(start, end)).join('\n\n')
  .replace(/\n@font-face \{\s*font-family: 'JetBrains Mono';[\s\S]*?font-display: swap;\s*\}\n/, '\n');
const deepWithPlaceholders = `${header}\n${deepBody}\n\n${placeholders}\n`;
fs.writeFileSync(OUT_PATH, deepWithPlaceholders, 'utf8');
console.log(`deep-core.css: ${Buffer.byteLength(deepWithPlaceholders)} bytes`);

const videoBoatHeader = `/* Generated by scripts/build-deep-core-css.js.
   Source: css/style.css
   Purpose: lazy CSS for lower video + boat close sections. */
`;
const videoBoatOutput = `${videoBoatHeader}\n${videoBoatSlices.map(([start, end]) => readSlice(start, end)).join('\n\n')}\n`;
fs.writeFileSync(VIDEO_BOAT_OUT_PATH, videoBoatOutput, 'utf8');
console.log(`video-boat.css: ${Buffer.byteLength(videoBoatOutput)} bytes`);

const featuresDeptHeader = `/* Generated by scripts/build-deep-core-css.js.
   Source: css/style.css
   Purpose: Features-only department chat modal CSS. */
`;
const featuresDeptOutput = `${featuresDeptHeader}\n${readSlice('/* ─── DEPT CHAT MODAL ─── */', '/* ─── MOBILE NAV ─── */')}\n`;
fs.writeFileSync(FEATURES_DEPT_OUT_PATH, featuresDeptOutput, 'utf8');
console.log(`features-dept.css: ${Buffer.byteLength(featuresDeptOutput)} bytes`);
