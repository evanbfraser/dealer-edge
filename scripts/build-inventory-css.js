const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CSS_DIR = path.join(ROOT, 'css');
const SOURCE_PATH = path.join(CSS_DIR, 'inventory.css');
const css = fs.readFileSync(SOURCE_PATH, 'utf8');

function readSlice(startMarker, endMarker) {
  const start = css.indexOf(startMarker);
  if (start === -1) throw new Error(`Missing start marker: ${startMarker}`);
  const end = endMarker ? css.indexOf(endMarker, start + startMarker.length) : css.length;
  if (endMarker && end === -1) throw new Error(`Missing end marker: ${endMarker}`);
  return css.slice(start, end).trim();
}

function write(file, body, purpose) {
  const header = `/* Generated by scripts/build-inventory-css.js.
   Source: css/inventory.css
   Purpose: ${purpose}. */
`;
  const output = `${header}\n${body.trim()}\n`;
  fs.writeFileSync(path.join(CSS_DIR, file), output, 'utf8');
  console.log(`${file}: ${Buffer.byteLength(output)} bytes`);
}

const includesMarker = 'STATIC SECTION';
const includesIndex = css.indexOf(includesMarker);
if (includesIndex === -1) throw new Error(`Missing marker: ${includesMarker}`);
const includesCommentStart = css.lastIndexOf('/*', includesIndex);
if (includesCommentStart === -1) throw new Error('Missing includes comment start');

const heroBase = css.slice(0, includesCommentStart).trim();
const heroMobile1100 = `${readSlice('@media (max-width: 1100px)', '  .i-buried {')}\n}`;
const heroMobile640 = `${readSlice('@media (max-width: 640px)', '  .i-buried-rows {')}\n}`;
const late = css.slice(includesCommentStart).trim();

write(
  'inventory-critical.css',
  [heroBase, heroMobile1100, heroMobile640].join('\n\n'),
  'critical inventory hero CSS'
);

write(
  'inventory-late.css',
  late,
  'below-fold inventory includes, compare, acts, and responsive refinements'
);
