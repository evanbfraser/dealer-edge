const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const STYLE_PATH = path.join(ROOT, 'css', 'style.css');
const CSS_DIR = path.join(ROOT, 'css');

const css = fs.readFileSync(STYLE_PATH, 'utf8');

function readSlice(startMarker, endMarker) {
  const start = css.indexOf(startMarker);
  if (start === -1) throw new Error(`Missing start marker: ${startMarker}`);
  const end = endMarker ? css.indexOf(endMarker, start + startMarker.length) : css.length;
  if (endMarker && end === -1) throw new Error(`Missing end marker: ${endMarker}`);
  return css.slice(start, end).trim();
}

const common = [
  ['/* ─── VARIABLES ─── */', '/* ─── HERO ─── */'],
  ['/* ─── BUTTONS ─── */', '/* ─── FEATURES ─── */'],
  ['.features-cta-actions {', '/* ─── JOURNEY / TOUCHPOINTS ─── */'],
  ['/* ─── CTA ─── */', '/* ─── CHATBOT ─── */'],
  ['/* ─── MODAL ─── */', '/* ─── PRICING PAGE ─── */'],
];

const responsiveShell = [
  ['/* ─── MOBILE NAV ─── */', '/* ─── VIDEO + BOAT RESPONSIVE ─── */'],
  ['/* ─── MODAL MOBILE ─── */', null],
];

const outputs = {
  'home-core.css': [
    ['/* ─── VARIABLES ─── */', '/* ─── VIDEO SECTION ─── */'],
    ['/* ─── RESET ─── */', '/* ─── FEATURES ─── */'],
    ['/* ─── RESPONSIVE ─── */', '/* ─── CHATBOT ─── */'],
    ['/* ─── CHATBOT ─── */', '/* ─── PRICING PAGE ─── */'],
    ...responsiveShell,
  ],
  'home-late.css': [
    ['/* ─── VIDEO SECTION ─── */', '/* ─── RESET ─── */'],
    ['/* ─── BOAT SECTION ─── */', '/* ─── ANIMATION INITIAL STATE ─── */'],
    ['/* ─── FEATURES ─── */', '/* ─── CHATBOT ─── */'],
    ['/* ─── VIDEO + BOAT RESPONSIVE ─── */', '/* ─── MODAL MOBILE ─── */'],
  ],
  'pricing-core.css': [
    ...common,
    ['/* ─── PRICING PAGE ─── */', '/* ─── CASE STUDIES PAGE ─── */'],
    ...responsiveShell,
  ],
  'results-core.css': [
    ...common,
    ['/* ─── CASE STUDIES PAGE ─── */', '/* ─── READING PROGRESS BAR ─── */'],
    ...responsiveShell,
  ],
};

for (const [file, slices] of Object.entries(outputs)) {
  const header = `/* Generated by scripts/build-page-core-css.js.
   Source: css/style.css
   Purpose: lean shared CSS for ${file.replace('-core.css', '')} pages. */
`;
  const output = `${header}\n${slices.map(([start, end]) => readSlice(start, end)).join('\n\n')}\n`;
  const outPath = path.join(CSS_DIR, file);
  fs.writeFileSync(outPath, output, 'utf8');
  console.log(`${file}: ${Buffer.byteLength(output)} bytes`);
}
