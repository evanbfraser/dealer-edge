const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CSS_DIR = path.join(ROOT, 'css');
const SOURCE_PATH = path.join(CSS_DIR, 'marketing.css');
const css = fs.readFileSync(SOURCE_PATH, 'utf8');

function readSlice(startMarker, endMarker) {
  const start = css.indexOf(startMarker);
  if (start === -1) throw new Error(`Missing start marker: ${startMarker}`);
  const end = endMarker ? css.indexOf(endMarker, start + startMarker.length) : css.length;
  if (endMarker && end === -1) throw new Error(`Missing end marker: ${endMarker}`);
  return css.slice(start, end).trim();
}

function write(file, body, purpose) {
  const header = `/* Generated by scripts/build-marketing-css.js.
   Source: css/marketing.css
   Purpose: ${purpose}. */
`;
  const output = `${header}\n${body.trim()}\n`;
  fs.writeFileSync(path.join(CSS_DIR, file), output, 'utf8');
  console.log(`${file}: ${Buffer.byteLength(output)} bytes`);
}

const activeFlowHero = readSlice(
  '/* ═══════════════════════════════════════════════════════════════',
  '/* ---- (legacy radial engine removed — replaced by .m-flow above) ---- */'
);
const heroNext = readSlice('.m-hero-next {', '/* Shared sections */');
const responsive1180 = `${readSlice('@media (max-width: 1180px)', '  .m-website-chaos {')}\n}`;
const mobileHero1100 = `${readSlice('@media (max-width: 1100px)', '  .m-hero-boards {')}\n}`;
const mobileHero520 = `${readSlice('@media (max-width: 520px)', '  .m-hero-boards {')}\n}`;
const reducedMotion = readSlice('@media (prefers-reduced-motion: reduce)', '/* Website-act morph beats — narrow-screen fit */');

write(
  'marketing-critical.css',
  [activeFlowHero, heroNext, responsive1180, mobileHero1100, mobileHero520, reducedMotion].join('\n\n'),
  'critical pinned marketing hero CSS'
);

write(
  'marketing-late.css',
  readSlice('/* Shared sections */', null),
  'below-fold marketing showcase, acts, pillar nav, and responsive refinements'
);
