const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CSS_DIR = path.join(ROOT, 'css');
const SOURCE_PATH = path.join(CSS_DIR, 'analytics.css');
const css = fs.readFileSync(SOURCE_PATH, 'utf8');

function readSlice(startMarker, endMarker) {
  const start = css.indexOf(startMarker);
  if (start === -1) throw new Error(`Missing start marker: ${startMarker}`);
  const end = endMarker ? css.indexOf(endMarker, start + startMarker.length) : css.length;
  if (endMarker && end === -1) throw new Error(`Missing end marker: ${endMarker}`);
  return css.slice(start, end).trim();
}

function write(file, body, purpose) {
  const header = `/* Generated by scripts/build-analytics-css.js.
   Source: css/analytics.css
   Purpose: ${purpose}. */
`;
  const output = `${header}\n${body.trim()}\n`;
  fs.writeFileSync(path.join(CSS_DIR, file), output, 'utf8');
  console.log(`${file}: ${Buffer.byteLength(output)} bytes`);
}

const staticMarker = 'STATIC SECTION';
const staticIndex = css.indexOf(staticMarker);
if (staticIndex === -1) throw new Error(`Missing marker: ${staticMarker}`);
const staticCommentStart = css.lastIndexOf('/*', staticIndex);
if (staticCommentStart === -1) throw new Error('Missing static section comment start');

const heroBase = css.slice(0, staticCommentStart).trim();
const heroMobile1100 = `${readSlice('@media (max-width: 1100px)', '  .a2-pdf {')}\n}`;
const heroMobile640 = `${readSlice('@media (max-width: 640px)', '  .a2-tabs-grid {')}\n}`;
const late = css.slice(staticCommentStart).trim();

write(
  'analytics-critical.css',
  [heroBase, heroMobile1100, heroMobile640].join('\n\n'),
  'critical analytics hero CSS'
);

write(
  'analytics-late.css',
  late,
  'below-fold analytics includes, acts, and responsive refinements'
);
